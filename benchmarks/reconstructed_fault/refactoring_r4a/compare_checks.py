#!/usr/bin/env python3
"""Exact solver/rollback and ordinary feature-disabled matched comparisons."""
from pathlib import Path
import json,re
root=Path(__file__).resolve().parent;e=root/'evidence';checks={}
markers=('line search accepted after','Stage-I rollback after an accepted Newton update: verified',
         'Relative nonlinear residuals (bulk, fault)', 'Fault linear solve:', 'Timestep ',
         'All tests passed', 'Solving Stokes system', 'Solving temperature system')
for name in ('unit-1','unit-2','rollback-original-1','rollback-original-2','ordinary-amg'):
    records=[json.loads((e/f'{v}-{name}.json').read_text()) for v in ('reference','candidate')]
    checks[name+'/exit']=all(r['exit_code']==0 for r in records)
    logs=[(e/f'{v}-{name}.log').read_text(errors='replace') for v in ('reference','candidate')]
    summaries=[sorted(line.strip() for line in s.splitlines() if any(m in line for m in markers)) for s in logs]
    checks[name+'/solver-decisions']=bool(summaries[0]) and summaries[0]==summaries[1]
    if name.startswith('rollback'):
        checks[name+'/accepted-update-and-restoration']=all('line search accepted after' in s and 'Stage-I rollback after an accepted Newton update: verified' in s for s in logs)
    if name=='ordinary-amg':
        paths=[root/f'output-{v}-{name}' for v in ('reference','candidate')]
        # Output directory is the sole expected path difference in statistics.
        stats=[(p/'statistics').read_text().replace(str(p),'<output>').replace(str(p.relative_to(root.parents[2])),'<output>') for p in paths]
        checks[name+'/statistics']=stats[0]==stats[1]
        for sub in ('solution','particles'):
            fields=[{p.name:re.sub(rb'#This file was generated by the deal.II library on [^\n]*', b'#generation timestamp omitted',p.read_bytes()) for p in (d/sub).glob('*.vtu')} for d in paths]
            checks[name+'/'+sub]=bool(fields[0]) and fields[0]==fields[1]
        checks[name+'/ordinary-iterative-path']=all('Solving Stokes system' in s and 'Reconstructed-fault' not in s for s in logs)
(e/'focused-comparison.json').write_text(json.dumps(checks,indent=2)+'\n')
print(json.dumps(checks,indent=2));assert all(checks.values())
