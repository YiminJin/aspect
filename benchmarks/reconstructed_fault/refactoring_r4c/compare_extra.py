#!/usr/bin/env python3
from pathlib import Path
import json,re,csv
r=Path(__file__).resolve().parent;e=r/'evidence';checks={}
markers=('Solving Stokes system','Solving temperature system','Timestep ','Relative nonlinear residual','Fault linear solve:','line search accepted after')
for name in ('ordinary-amg','bfbt','melt','fail-s','fail-budget'):
 logs=[(e/f'{v}-{name}.log').read_text(errors='replace').replace('\x00','') for v in ('reference','candidate')]
 records=[json.loads((e/f'{v}-{name}.json').read_text()) for v in ('reference','candidate')]
 checks[name+'/outcome']=all(j['exit_code']==(1 if name.startswith('fail-') else 0) for j in records)
 summaries=[sorted(s.strip() for s in log.splitlines() if any(m in s for m in markers)) for log in logs]
 checks[name+'/decisions']=bool(summaries[0]) and summaries[0]==summaries[1]
 ds=[r/f'output-{v}-{name}' for v in ('reference','candidate')]
 if name.startswith('fail-'):
  histories=[(d/'solver_history.txt').read_text() for d in ds]
  checks[name+'/failure-history']=bool(histories[0]) and histories[0]==histories[1]
  residuals=[re.findall(r'The (?:initial residual was|final residual is|required residual for convergence is): [^\n]+',s) for s in logs]
  checks[name+'/failure-residuals']=bool(residuals[0]) and residuals[0]==residuals[1]
  key='iterative (bottom right) solver' if name=='fail-s' else 'failure in step 10'
  checks[name+'/specific-failure']=all(key in s for s in logs)
 else:
  stats=[(d/'statistics').read_text().replace(str(d),'<output>').replace(str(d.relative_to(r.parents[2])),'<output>') for d in ds]
  checks[name+'/statistics']=bool(stats[0]) and stats[0]==stats[1]
  for sub in ('solution','particles'):
   fields=[{p.name:re.sub(rb'#This file was generated by the deal.II library on [^\n]*',b'#timestamp omitted',p.read_bytes()) for p in (d/sub).glob('*.vtu')} for d in ds]
   if any(fields):checks[name+'/'+sub]=bool(fields[0]) and fields[0]==fields[1]
(e/'extra-comparison.json').write_text(json.dumps(checks,indent=2)+'\n');print(json.dumps(checks,indent=2));assert all(checks.values())
