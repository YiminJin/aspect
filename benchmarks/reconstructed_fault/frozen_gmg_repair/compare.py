#!/usr/bin/env python3
"""Check complete frozen solves, exact pre/post-R4c equivalence and old AMG continuity."""
from pathlib import Path
import csv, hashlib, json, re
root = Path(__file__).resolve().parent
repo = root.parents[2]
evidence = root/'evidence'
old = root.with_name('refactoring_r4c')
versions = ('reference', 'candidate')
checks = {}
def parameters(path):
    def flatten(tree, prefix=''):
        result = {}
        for key, value in tree.items():
            name = prefix+key
            if 'alias' in value:
                continue
            if 'value' in value:
                result[name] = value['value']
            else:
                result.update(flatten(value, name+'/'))
        return result
    return flatten(json.loads(path.read_text()))

def work_counts(log):
    return [re.findall(r'(?:step|newton|\w+_calls)=\d+', line)
            for line in log.splitlines() if line.startswith('Fault linear profile:')]

logs = [(evidence/f'{v}-run.log').read_text(errors='replace') for v in versions]
rows = []
keys = ('backend', 'step', 'newton', 'rhs_norm', 'tolerance', 'iterations', 'fresh',
        'estimated', 'direction_difference_relative', 'preconditioner_calls', 'operator_calls')
pass_marker = 'FROZEN AMG/GMG COMPARISON PASSED; intentional stop before trial/history commit.'
stop_marker = 'Intentional frozen GMG comparison stop.'
for version, log in zip(versions, logs):
    record = json.loads((evidence/f'{version}-run.json').read_text())
    checks[version+'/intentional-stop-after-complete-pass'] = (
        record['exit_code'] == 1 and pass_marker in log and stop_marker in log
        and log.index(pass_marker) < log.index(stop_marker))
    checks[version+'/actual-backends'] = ('production=block AMG; hierarchy=present' in log
        and 'Frozen GMG velocity cycle applied on every rank.' in log)
    checks[version+'/state-preservation'] = ('Frozen state and RHS preserved exactly on every rank; operator actions unchanged.' in log)
    checks[version+'/original-mesh'] = ('cells=42968, extra grading leaves=0' in log
        and 'vertices=1236, coordinate error=0' in log)
    with (root/f'output-{version}/frozen_gmg.csv').open() as stream:
        data = list(csv.DictReader(stream))
    rows.append(data)
    checks[version+'/two-true-residuals'] = ([x['backend'] for x in data] == ['AMG','GMG']
        and all(0 <= float(x['fresh']) <= float(x['tolerance']) for x in data))
    checks[version+'/same-RHS-target'] = all(data[0][k] == data[1][k] for k in ('step','newton','rhs_norm','tolerance'))
    checks[version+'/AMG-reproduces-production-direction'] = float(data[0]['direction_difference_relative']) == 0
    with (root/f'output-{version}/accepted_steps.csv').open() as stream:
        checks[version+'/no-step-two-publication'] = [int(x['step']) for x in csv.DictReader(stream)] == [0,1]
checks['pre-post/numerics-and-work'] = [[{k:x[k] for k in keys} for x in data] for data in rows][0] == [[{k:x[k] for k in keys} for x in data] for data in rows][1]
markers = ('Fault linear solve:', 'Relative nonlinear residuals', 'line search accepted after', '*** Timestep')
def decisions(log):
    return [x.strip() for x in log.splitlines() if any(m in x for m in markers)]
checks['pre-post/production-decisions'] = bool(decisions(logs[0])) and decisions(logs[0]) == decisions(logs[1])
checks['pre-post/production-work-counts'] = bool(work_counts(logs[0])) and work_counts(logs[0]) == work_counts(logs[1])

def fields(left, right, label):
    paths = sorted(p.name for p in left.glob('*.csv') if p.name != 'frozen_gmg.csv')
    paths += sorted(p.name for p in left.glob('bulk_*.vtu'))
    assert paths
    for name in paths:
        # VTU carries a wall-clock comment; all actual fields/connectivity must match.
        def payload(p):
            return re.sub(rb'#This file was generated by the deal.II library on [^\n]*', b'#timestamp omitted', p.read_bytes())
        checks[label+'/'+name] = (right/name).is_file() and payload(left/name) == payload(right/name)

fields(root/'output-reference', root/'output-candidate', 'pre-post/fields')
for version, log, data in zip(versions, logs, rows):
    historical = old/f'output-{version}-frozen-replay'
    fields(historical, root/f'output-{version}', version+'/historical-fields')
    with (historical/'frozen_gmg.csv').open() as stream:
        historical_row = next(csv.DictReader(stream))
    checks[version+'/historical-AMG'] = all(data[0][k] == historical_row[k] for k in keys)
    old_log = (old/f'evidence/{version}-frozen-replay.log').read_text(errors='replace')
    checks[version+'/historical-production-decisions'] = decisions(log) == decisions(old_log)
    old_counts, new_counts = work_counts(old_log), work_counts(log)
    checks[version+'/historical-pre-observer-work-counts'] = old_counts[:-1] == new_counts[:-1]
    # The final profile is emitted during exception cleanup, after the observer.
    # The repaired callback adds 17 GMG operator calls, its fresh residual call,
    # and four before/after operator audits: exactly 22, all outside the prefix.
    last = [dict((k,int(v)) for k,v in (entry.split('=') for entry in counts[-1]))
            for counts in (old_counts,new_counts)]
    added_actions = {'inverse_calls', 'A_calls', 'other_calls', 'B_sparse_calls', 'G_sparse_calls'}
    checks[version+'/historical-final-probe-work-delta'] = (
        last[0]['step'] == last[1]['step'] == 2 and last[0]['newton'] == last[1]['newton'] == 4
        and last[0].keys() == last[1].keys()
        and all(last[1][k]-last[0][k] == (22 if k in added_actions else 0) for k in last[0]))
    before = parameters(historical/'parameters.json')
    after = parameters(root/f'output-{version}/parameters.json')
    changes = {k for k in before.keys() | after.keys() if before.get(k) != after.get(k)}
    checks[version+'/only-fixture-parameter-changes'] = changes == {
        'Additional shared libraries', 'Output directory',
        'Solver parameters/Stokes solver parameters/Stokes solver type'}
# Rank-local binary evidence contains all owned bulk fields, serialized manager
# histories, current V/masks, particles, RHS/direction and two operator probes.
for name in ('frozen_state','frozen_operator_direction','frozen_operator_rhs','frozen_direction_AMG','frozen_direction_GMG'):
    for rank in range(4):
        a = root/f'output-reference/{name}.{rank}.bin'
        b = root/f'output-candidate/{name}.{rank}.bin'
        checks[f'pre-post/{name}/rank{rank}'] = a.is_file() and b.is_file() and a.read_bytes() == b.read_bytes()
for p, expected in json.loads((evidence/'protected-hashes.json').read_text()).items():
    assert hashlib.sha256((repo/p).read_bytes()).hexdigest() == expected, p
record = dict(checks=checks, matched_rows=[{k:x[k] for k in keys} for x in rows[0]],
              failures=[k for k,v in checks.items() if not v], count=len(checks))
(evidence/'comparison.json').write_text(json.dumps(record, indent=2)+'\n')
print(json.dumps({k:v for k,v in record.items() if k != 'checks'}, indent=2))
assert all(checks.values())
