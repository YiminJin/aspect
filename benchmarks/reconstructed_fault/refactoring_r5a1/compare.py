#!/usr/bin/env python3
"""Compare only the selected lifecycle checks at matched rank counts."""
from pathlib import Path
import json,re,hashlib
r=Path(__file__).resolve().parent;e=r/'evidence';old=r.with_name('refactoring_r4c');checks={}
ansi=re.compile(r'\x1b\[[0-9;]*m')
def log(path):return ansi.sub('',path.read_text(errors='replace')).replace('\x00','')
markers=('line search accepted after','Stage-I rollback after an accepted Newton update: verified',
 'Relative nonlinear residuals (bulk, fault)', 'Fault linear solve:', 'Timestep ', 'All tests passed',
 'Coupled pressure gauge:', 'Reconstructed-fault Stage-I solve:', 'Changed loading:')
def decisions(text):return sorted(x.strip() for x in text.splitlines() if any(m in x for m in markers))
for rank in (1,2):
 for name in ('unit','pressure','rollback-original'):
  aroot,av=(r,'reference') if name=='unit' else (old,'candidate')
  a=log(aroot/f'evidence/{av}-{name}-{rank}.log');b=log(e/f'candidate-{name}-{rank}.log')
  outcomes=[json.loads(p.read_text())['exit_code'] for p in (aroot/f'evidence/{av}-{name}-{rank}.json',e/f'candidate-{name}-{rank}.json')]
  key=f'{name}-{rank}'
  checks[key+'/pass']=outcomes==[0,0]
  checks[key+'/exact-decisions']=bool(decisions(a)) and decisions(a)==decisions(b)
  if name=='unit':checks[key+'/all-ranks']=b.count('All tests passed (20130 assertions in 7 test cases)')==rank
  if name=='rollback-original':checks[key+'/accepted-update-rollback']=all('line search accepted after' in s and 'Stage-I rollback after an accepted Newton update: verified' in s for s in (a,b))
  if name=='pressure':
   da=aroot/f'output-{av}-{name}-{rank}';db=r/f'output-candidate-{name}-{rank}'
   states=[{p.name:p.read_bytes() for p in d.glob('gauge-state-*.txt')} for d in (da,db)]
   checks[key+'/histories']=bool(states[0]) and states[0]==states[1]
   for sub in ('solution','particles'):
    def files(d):return {p.name:re.sub(rb'#This file was generated by the deal.II library on [^\n]*',b'#timestamp omitted',p.read_bytes()) for p in (d/sub).glob('*.vtu')}
    aa,bb=files(da),files(db)
    if aa or bb:checks[key+'/'+sub]=bool(aa) and aa==bb

restarts=[log(e/f'{v}-restart.log') for v in ('reference','candidate')]
for v,s in zip(('reference','candidate'),restarts):
 checks[v+'/checkpoint-load']= 'Stage-J checkpoint histories, V, geometry, and bulk: verified' in s
 checks[v+'/known-step-two-failure']= json.loads((e/f'{v}-restart.json').read_text())['exit_code']==1 and 'Newton line search exhausted all admissible candidates' in s and 'Nonlinear solver failed to converge' in s
 checks[v+'/no-crash']= 'Segmentation fault' not in s and 'Invalid reconstructed-fault' not in s
checks['restart/exact-solver-decisions']=bool(decisions(restarts[0])) and decisions(restarts[0])==decisions(restarts[1])
# Check the full phase-field and coupled trace in order, including precision formatting.
trace_markers=('Iteration ', 'Fault linear solve:', 'Relative nonlinear residuals', 'line search accepted after',
 'Solving temperature system', 'Phase-field residual target:', 'Stage-J history resolution:', 'Stage-J feedback step')
traces=[[x.strip() for x in s.splitlines() if any(m in x for m in trace_markers)] for s in restarts]
checks['restart/exact-full-trace']=bool(traces[0]) and traces[0]==traces[1]
for name in ('mesh','mesh.info','mesh_fixed.data','mesh_variable.data','resume.z'):
 original=r.with_name('restart_investigation')/'output-create-one/restart/01'/name
 checks['restart/preserved-checkpoint/'+name]=all((r/f'output-{v}-restart/restart/01'/name).read_bytes()==original.read_bytes() for v in ('reference','candidate'))
(e/'comparison.json').write_text(json.dumps(checks,indent=2)+'\n')
print(len(checks),'checks; failures:',[k for k,v in checks.items() if not v]);assert all(checks.values())
